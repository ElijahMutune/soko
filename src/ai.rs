use axum::{extract::State, http::HeaderMap, Json};
use base64::{engine::general_purpose::STANDARD as BASE64, Engine};
use serde::{Deserialize, Serialize};
use sqlx::Row;
use std::collections::HashSet;
use uuid::Uuid;

use crate::{auth::routes::authenticated_user_id, error::AppError, state::AppState};

#[derive(Debug, Deserialize)]
pub struct SuggestionRequest {
    /// Backwards-compatible single-image input.
    #[serde(default)]
    pub image_id: Option<Uuid>,
    /// Up to 8 seller-owned uploaded images, representing different views of the same item.
    #[serde(default)]
    pub image_ids: Option<Vec<Uuid>>,
}

#[derive(Debug, Serialize, Deserialize)]
pub struct ListingSuggestion {
    pub title: String,
    pub description: String,
    pub category_name: String,
    pub color: Option<String>,
    pub brand: Option<String>,
    pub condition_guess: String,
    pub seller_review_notes: String,
}

#[derive(Debug, Deserialize)]
struct GroqResponse {
    choices: Vec<GroqChoice>,
}

#[derive(Debug, Deserialize)]
struct GroqChoice {
    message: GroqMessage,
    finish_reason: Option<String>,
}

#[derive(Debug, Deserialize)]
struct GroqMessage {
    content: String,
}

#[derive(Debug, Deserialize)]
struct GroqErrorEnvelope {
    error: Option<GroqApiError>,
}

#[derive(Debug, Deserialize)]
struct GroqApiError {
    message: Option<String>,
    code: Option<serde_json::Value>,
    #[serde(rename = "type")]
    error_type: Option<String>,
}

pub async fn suggest_listing(
    State(state): State<AppState>,
    headers: HeaderMap,
    Json(input): Json<SuggestionRequest>,
) -> Result<Json<ListingSuggestion>, AppError> {
    let owner_id = authenticated_user_id(&state, &headers).await?;

    // Accept either the legacy single image_id or the new ordered image_ids array.
    // The ordered list represents several views of the same product.
    const MAX_AI_IMAGES: usize = 8;
    const MAX_AI_IMAGE_BYTES: usize = 24 * 1024 * 1024;
    let image_ids = match (input.image_id, input.image_ids) {
        (Some(single), None) => vec![single],
        (None, Some(multiple)) => multiple,
        (Some(single), Some(multiple)) if multiple.is_empty() => vec![single],
        (Some(_), Some(_)) => {
            return Err(AppError::BadRequest("Provide image_id or image_ids, not both".into()));
        }
        (None, None) => {
            return Err(AppError::BadRequest("Provide image_id or image_ids".into()));
        }
    };
    if image_ids.is_empty() || image_ids.len() > MAX_AI_IMAGES {
        return Err(AppError::BadRequest("AI can analyse between 1 and 8 product images".into()));
    }
    let unique_ids: HashSet<Uuid> = image_ids.iter().copied().collect();
    if unique_ids.len() != image_ids.len() {
        return Err(AppError::BadRequest("Duplicate image IDs are not allowed".into()));
    }

    #[derive(Debug, sqlx::FromRow)]
    struct AiImageRow {
        id: Uuid,
        file_name: String,
        mime_type: String,
    }

    // Only use images uploaded by this seller. Validate every ID before logging
    // the AI request, so another seller's or missing image cannot reach the provider.
    let image_rows = sqlx::query_as::<_, AiImageRow>(
        "SELECT id, file_name, mime_type FROM uploaded_images WHERE id = ANY($1) AND owner_id = $2 AND storage_provider = 'local'",
    )
    .bind(&image_ids[..])
    .bind(owner_id)
    .fetch_all(&state.db)
    .await?;
    if image_rows.len() != image_ids.len() {
        return Err(AppError::NotFound);
    }
    let mut image_map = image_rows.into_iter().map(|row| (row.id, row)).collect::<std::collections::HashMap<_, _>>();
    let mut images: Vec<(String, Vec<u8>)> = Vec::with_capacity(image_ids.len());
    let mut total_image_bytes = 0usize;
    for image_id in &image_ids {
        let image = image_map.remove(image_id).ok_or(AppError::NotFound)?;
        // Filenames are generated by the server as UUID + fixed extension. Check
        // the DB value again before joining it to the local upload directory.
        if std::path::Path::new(&image.file_name).file_name().and_then(|v| v.to_str())
            != Some(image.file_name.as_str())
        {
            return Err(AppError::NotFound);
        }
        let bytes = tokio::fs::read(std::path::Path::new("uploads").join(&image.file_name))
            .await
            .map_err(|_| AppError::NotFound)?;
        total_image_bytes = total_image_bytes.saturating_add(bytes.len());
        if total_image_bytes > MAX_AI_IMAGE_BYTES {
            return Err(AppError::BadRequest("Combined image size for AI analysis must be 24 MB or smaller".into()));
        }
        images.push((image.mime_type, bytes));
    }

    let api_key = std::env::var("GROQ_API_KEY").map_err(|_| AppError::AiUnavailable)?;
    if api_key.trim().is_empty() {
        return Err(AppError::AiUnavailable);
    }
    let model = std::env::var("GROQ_VISION_MODEL")
        .unwrap_or_else(|_| "qwen/qwen3.8-27b".to_string());
    // Model names come from server configuration, never from the request body.
    // The slash is part of Groq's published model IDs.
    if model.is_empty()
        || !model
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '.' | '/' | '_'))
    {
        tracing::error!("Invalid GROQ_VISION_MODEL configuration");
        return Err(AppError::AiUnavailable);
    }

    // Reserve an AI request under a per-user row lock before calling the external AI API.
    // Failed upstream attempts count too, which prevents repeated cost-heavy retries.
    let mut usage_tx = state.db.begin().await?;
    sqlx::query("SELECT id FROM users WHERE id = $1 FOR UPDATE")
        .bind(owner_id)
        .fetch_one(&mut *usage_tx)
        .await?;
    let recent_ai_calls: i64 = sqlx::query_scalar(
        "SELECT COUNT(*) FROM ai_listing_requests WHERE owner_id = $1 AND created_at > NOW() - INTERVAL '1 hour'",
    )
    .bind(owner_id)
    .fetch_one(&mut *usage_tx)
    .await?;
    if recent_ai_calls >= 10 {
        return Err(AppError::RateLimited);
    }
    sqlx::query("INSERT INTO ai_listing_requests (owner_id, uploaded_image_id) VALUES ($1, $2)")
        .bind(owner_id)
        .bind(image_ids[0])
        .execute(&mut *usage_tx)
        .await?;
    usage_tx.commit().await?;

    let category_rows = sqlx::query(
        "SELECT name FROM categories WHERE is_active = TRUE ORDER BY sort_order, name",
    )
    .fetch_all(&state.db)
    .await?;
    let categories: Vec<String> = category_rows
        .iter()
        .map(|row| row.try_get::<String, _>("name"))
        .collect::<Result<_, _>>()?;
    let category_list = categories.join(", ");

    let system_prompt = format!(
        "You create accurate marketplace listing drafts for a Kenya-based second-hand marketplace. You will receive {image_count} photographs of one product, possibly showing different angles or details. Treat them as views of the same item, not separate products. Combine only facts visibly supported across the images. If images appear to show different products or contradictory details, mention that in seller_review_notes and avoid guessing. Do not invent a brand, model, size, material, authenticity, functionality, age, or hidden product specifications. Set brand to null unless the brand name is clearly visible. Do not claim an item works or is tested. Keep the description concise, neutral, and useful. Choose category_name from this exact list: [{category_list}]. If uncertain, use Other. Do not set a price; the seller will choose the price. Return valid JSON only with keys: title, description, category_name, color, brand, condition_guess, seller_review_notes. condition_guess must be one of: new, like new, good, fair, poor, unknown. seller_review_notes should briefly remind the seller to verify details that cannot be established visually. Use null for color or brand when uncertain.",
        image_count = images.len()
    );
    let user_prompt = "Create one draft listing suggestion for the single product shown across these photographs. Be factual and avoid unsupported claims.";

    // Groq's Chat Completions API accepts OpenAI-compatible multimodal messages.
    // The seller's ordered views are sent in one AI request; only this first
    // image ID is written to the existing usage ledger for compatibility.
    let mut user_content = vec![serde_json::json!({ "type": "text", "text": user_prompt })];
    for (mime_type, bytes) in &images {
        let image_base64 = BASE64.encode(bytes);
        let data_url = format!("data:{mime_type};base64,{image_base64}");
        user_content.push(serde_json::json!({
            "type": "image_url",
            "image_url": { "url": data_url }
        }));
    }
    let request_body = serde_json::json!({
        "model": model,
        "messages": [
            { "role": "system", "content": system_prompt },
            {
                "role": "user",
                "content": user_content
            }
        ],
        "response_format": { "type": "json_object" },
        "temperature": 0.2,
        "max_completion_tokens": 700,
        "stream": false
    });

    let client = reqwest::Client::builder()
        .timeout(std::time::Duration::from_secs(60))
        .build()
        .map_err(|error| {
            tracing::error!(error = %error, "Could not create Groq HTTP client");
            AppError::AiUnavailable
        })?;

    let response = client
        .post("https://api.groq.com/openai/v1/chat/completions")
        .bearer_auth(api_key)
        .json(&request_body)
        .send()
        .await
        .map_err(|error| {
            tracing::error!(error = %error, "Groq listing suggestion transport failed");
            AppError::ExternalService
        })?;

    if !response.status().is_success() {
        let status = response.status();
        let retry_after = response
            .headers()
            .get(reqwest::header::RETRY_AFTER)
            .and_then(|value| value.to_str().ok())
            .unwrap_or("not provided")
            .to_string();
        let error_text = response.text().await.unwrap_or_default();
        let parsed_error = serde_json::from_str::<GroqErrorEnvelope>(&error_text).ok();
        if let Some(provider_error) = parsed_error.and_then(|envelope| envelope.error) {
            let message: String = provider_error
                .message
                .unwrap_or_default()
                .chars()
                .take(600)
                .collect();
            tracing::error!(
                http_status = %status,
                retry_after = %retry_after,
                provider_code = ?provider_error.code,
                provider_error_type = ?provider_error.error_type,
                provider_message = %message,
                "Groq listing suggestion request failed"
            );
        } else {
            tracing::error!(
                http_status = %status,
                retry_after = %retry_after,
                "Groq listing suggestion request failed; provider response was not valid JSON"
            );
        }
        return Err(AppError::ExternalService);
    }

    let response_body: GroqResponse = response.json().await.map_err(|error| {
        tracing::error!(error = %error, "Could not parse Groq response envelope");
        AppError::ExternalService
    })?;
    let choice = response_body.choices.first().ok_or_else(|| {
        tracing::error!("Groq returned no choices for listing suggestion");
        AppError::ExternalService
    })?;
    let content = choice.message.content.trim();
    if content.is_empty() {
        tracing::error!(finish_reason = ?choice.finish_reason, "Groq returned an empty listing suggestion");
        return Err(AppError::ExternalService);
    }
    let mut suggestion: ListingSuggestion = serde_json::from_str(content).map_err(|error| {
        tracing::error!(error = %error, "Groq returned listing suggestion that did not match the expected JSON shape");
        AppError::ExternalService
    })?;

    if !(3..=120).contains(&suggestion.title.trim().len())
        || suggestion.description.trim().len() > 3000
        || !categories
            .iter()
            .any(|name| name.eq_ignore_ascii_case(&suggestion.category_name))
        || !matches!(
            suggestion.condition_guess.to_ascii_lowercase().as_str(),
            "new" | "like new" | "good" | "fair" | "poor" | "unknown"
        )
    {
        return Err(AppError::ExternalService);
    }
    if let Some(canonical_category) = categories
        .iter()
        .find(|name| name.eq_ignore_ascii_case(&suggestion.category_name))
    {
        suggestion.category_name = canonical_category.clone();
    }

    Ok(Json(suggestion))
}
